#!/usr/bin/env python3
"""Regenerate src/syscall_tables.rs from the kernel's UAPI headers.

Raw audit records (`type=SYSCALL` / `type=SECCOMP`) carry only a syscall
number, so petrify needs a number -> name table per architecture. The tables
are vendored rather than read at runtime because the log being analysed
usually comes from a different machine than the one running petrify.

Needs the linux-libc-dev headers and `cpp`:

    python3 scripts/gen_syscall_tables.py
"""

from __future__ import annotations

import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "syscall_tables.rs"

X86_64_HEADER = Path("/usr/include/x86_64-linux-gnu/asm/unistd_64.h")
GENERIC_HEADER = Path("/usr/include/asm-generic/unistd.h")

# What arch/arm64/include/uapi/asm/unistd.h defines before including the
# generic table.
ARM64_DEFINES = [
    "-D__BITS_PER_LONG=64",
    "-D__ARCH_WANT_RENAMEAT",
    "-D__ARCH_WANT_NEW_STAT",
    "-D__ARCH_WANT_SET_GET_RLIMIT",
    "-D__ARCH_WANT_TIME32_SYSCALLS",
    "-D__ARCH_WANT_MEMFD_SECRET",
]

# Spot checks: a wrong table silently produces a wrong profile.
KNOWN = {
    "x86_64": {0: "read", 59: "execve", 257: "openat", 262: "newfstatat", 435: "clone3"},
    "aarch64": {
        25: "fcntl",
        38: "renameat",
        56: "openat",
        62: "lseek",
        63: "read",
        79: "newfstatat",
        80: "fstat",
        163: "getrlimit",
        221: "execve",
        222: "mmap",
        435: "clone3",
    },
}


def x86_64() -> dict[int, str]:
    table = {}
    for name, number in re.findall(
        r"^#define __NR_(\w+)\s+(\d+)$", X86_64_HEADER.read_text(), re.M
    ):
        table[int(number)] = name
    return table


def aarch64() -> dict[int, str]:
    """Let cpp resolve the header's conditionals, then read the macro table."""
    macros = subprocess.run(
        ["cpp", "-dM", "-nostdinc", "-undef", *ARM64_DEFINES, "-include", "/dev/null", "-"],
        input=_strip_includes(GENERIC_HEADER.read_text()),
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    defines = dict(re.findall(r"^#define (__NR\w*)\s+(\S+)$", macros, re.M))

    def resolve(value: str) -> int | None:
        seen = set()
        while not value.isdigit():
            if value in seen or value not in defines:
                return None
            seen.add(value)
            value = defines[value]
        return int(value)

    table = {}
    for macro, value in defines.items():
        if not macro.startswith("__NR_") or macro in (
            "__NR_syscalls",
            "__NR_arch_specific_syscall",
        ):
            continue
        number = resolve(value)
        if number is not None:
            table[number] = macro.removeprefix("__NR_")
    # The 64-bit kernel exposes these under their "new" names.
    table[79] = "newfstatat"
    return table


def _strip_includes(text: str) -> str:
    return re.sub(r"^#include.*$", "", text, flags=re.M)


def main() -> None:
    tables = {"x86_64": x86_64(), "aarch64": aarch64()}
    for arch, expected in KNOWN.items():
        for number, name in expected.items():
            got = tables[arch].get(number)
            if got != name:
                raise SystemExit(f"{arch}: syscall {number} resolved to {got!r}, expected {name!r}")

    lines = [
        "//! Syscall number -> name tables. Generated by scripts/gen_syscall_tables.py.",
        "",
        "use crate::events::Arch;",
        "",
        "/// The name of syscall `number` on `arch`, if the table knows it.",
        "pub fn name(arch: Arch, number: u32) -> Option<&'static str> {",
        "    let table = match arch {",
        "        Arch::X86_64 => X86_64,",
        "        Arch::Aarch64 => AARCH64,",
        "    };",
        "    let index = table.binary_search_by_key(&number, |&(n, _)| n).ok()?;",
        "    Some(table[index].1)",
        "}",
    ]
    for arch, table in tables.items():
        lines += ["", "#[rustfmt::skip]", f"static {arch.upper()}: &[(u32, &str)] = &["]
        lines += [f'    ({number}, "{table[number]}"),' for number in sorted(table)]
        lines.append("];")
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(
        f"wrote {OUT.relative_to(ROOT)}: " + ", ".join(f"{a}={len(t)}" for a, t in tables.items())
    )


if __name__ == "__main__":
    main()
