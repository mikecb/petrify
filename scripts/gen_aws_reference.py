#!/usr/bin/env python3
"""Regenerate src/sources/aws_reference.rs from AWS's Service Authorization
Reference.

For each IAM action of the listed services the reference says which resource
types the action can be limited to, and how the ARN of each type is written.
petrify needs both to scope a call correctly: an action limited to a resource
type it does not support is not granted at all.

    python3 scripts/gen_aws_reference.py

Needs network access to servicereference.us-east-1.amazonaws.com.
"""

from __future__ import annotations

import json
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "sources" / "aws_reference.rs"
URL = "https://servicereference.us-east-1.amazonaws.com/v1/{0}/{0}.json"

# The services whose calls petrify scopes from this table. Others have
# hand-written rules in cloudtrail.rs.
SERVICES = ["ec2", "iam", "rds"]

# An action that can involve more resource types than this (ec2:CreateTags
# takes 106) is left on "*" rather than listed type by type.
MAX_TYPES = 6

# Spot checks: a wrong table silently produces a wrong policy.
KNOWN_ACTIONS = {
    "iam": {"GetRole": ["role"], "AttachRolePolicy": ["role"], "ListRoles": []},
    "ec2": {"DeleteVpc": ["vpc"], "AttachVolume": ["instance", "volume"], "DescribeInstances": []},
    "rds": {"DeleteDBInstance": None, "DescribeDBEngineVersions": None},
}
KNOWN_ARNS = {
    "iam": {"role": "arn:${Partition}:iam::${Account}:role/${RoleNameWithPath}"},
    "ec2": {"image": "arn:${Partition}:ec2:${Region}::image/${ImageId}"},
    "rds": {"db": "arn:${Partition}:rds:${Region}:${Account}:db:${DbInstanceName}"},
}


def fetch(service: str) -> dict:
    with urllib.request.urlopen(URL.format(service), timeout=60) as response:
        return json.load(response)


def tables(reference: dict) -> tuple[dict[str, list[str] | None], dict[str, str]]:
    """(action -> resource types, or None when there are too many;
    resource type -> ARN format)."""
    actions: dict[str, list[str] | None] = {}
    for action in reference["Actions"]:
        types = sorted(r["Name"] for r in action.get("Resources") or [])
        actions[action["Name"]] = types if len(types) <= MAX_TYPES else None
    arns = {}
    for resource in reference["Resources"]:
        formats = resource["ARNFormats"]
        if len(formats) != 1:
            raise SystemExit(f"{resource['Name']}: expected one ARN format, found {formats}")
        arns[resource["Name"]] = formats[0]
    return actions, arns


def main() -> None:
    lines = [
        "//! Which resource types each IAM action can be limited to, and how their",
        "//! ARNs are written. Generated by scripts/gen_aws_reference.py from AWS's",
        "//! Service Authorization Reference.",
        "",
        "/// One service's part of the reference.",
        "pub struct Service {",
        "    /// Action -> the resource types it can be limited to, sorted by action.",
        "    /// Empty when the action only works on `*`; [`MANY`] when it takes more",
        "    /// types than are worth listing.",
        "    pub actions: &'static [(&'static str, &'static [&'static str])],",
        "    /// Resource type -> ARN format, sorted by type.",
        "    pub arns: &'static [(&'static str, &'static str)],",
        "}",
        "",
        "/// Stands in for the resource types of an action that takes too many.",
        'pub const MANY: &[&str] = &["*"];',
        "",
        "/// The reference for a service, by its IAM prefix.",
        "pub fn service(prefix: &str) -> Option<&'static Service> {",
        "    match prefix {",
    ]
    lines += [f'        "{s}" => Some(&{s.upper()}),' for s in SERVICES]
    lines += ["        _ => None,", "    }", "}"]

    counts = []
    for service in SERVICES:
        actions, arns = tables(fetch(service))
        for name, expected in KNOWN_ACTIONS[service].items():
            if name not in actions or (expected is not None and actions[name] != expected):
                raise SystemExit(f"{service}:{name} resolved to {actions.get(name)!r}")
        for name, expected in KNOWN_ARNS[service].items():
            if arns.get(name) != expected:
                raise SystemExit(f"{service} {name} ARN is {arns.get(name)!r}")
        counts.append(f"{service}={len(actions)} actions, {len(arns)} resource types")

        lines += ["", "#[rustfmt::skip]", f"static {service.upper()}: Service = Service {{", "    actions: &["]
        for name in sorted(actions):
            types = actions[name]
            listed = "MANY" if types is None else "&[" + ", ".join(f'"{t}"' for t in types) + "]"
            lines.append(f'        ("{name}", {listed}),')
        lines += ["    ],", "    arns: &["]
        lines += [f'        ("{name}", "{arns[name]}"),' for name in sorted(arns)]
        lines += ["    ],", "};"]
    lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: " + "; ".join(counts))


if __name__ == "__main__":
    main()
